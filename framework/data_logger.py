"""Thread-safe CSV logging for reproducible WAF experiments."""

from __future__ import annotations

import csv
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
import threading
from typing import Optional

try:
    from .config import CSV_COLUMNS, EnvironmentConfig
except ImportError:  # Supports: python framework/data_logger.py
    from config import CSV_COLUMNS, EnvironmentConfig


BLOCK_STATUS_CODES = {403, 406, 501}
REDIRECT_STATUS_CODES = {301, 302, 303, 307, 308}


@dataclass(frozen=True)
class RequestObservation:
    """One measured HTTP request generated by the framework."""

    phase: str
    load_level: str
    traffic_type: str
    attack_type: str
    request_name: str
    method: str
    url: str
    status_code: int
    response_time_ms: float
    result: str = "unknown"
    expected_behavior: str = "observed"
    timeout: bool = False
    detected_attack_type: str = "none"
    classification_result: str = "not_applicable"
    zap_alert_types: str = ""
    zap_alert_names: str = ""
    zap_alert_count: int = 0
    zap_high_alert_count: int = 0
    zap_medium_alert_count: int = 0
    zap_low_alert_count: int = 0
    error: Optional[str] = None


def utc_timestamp() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace(
        "+00:00", "Z"
    )


def blocked_flag(status_code: int) -> int:
    return 1 if status_code in BLOCK_STATUS_CODES else 0


def allowed_flag(status_code: int) -> int:
    return 1 if 200 <= status_code < 300 else 0


def redirect_flag(status_code: int) -> int:
    return 1 if status_code in REDIRECT_STATUS_CODES else 0


def client_error_flag(status_code: int) -> int:
    return 1 if 400 <= status_code < 500 and not blocked_flag(status_code) else 0


def server_error_flag(status_code: int) -> int:
    return 1 if status_code >= 500 else 0


def timeout_flag(observation: RequestObservation) -> int:
    return 1 if observation.timeout or observation.result == "timeout" else 0


def classify_result(status_code: int, timeout: bool = False) -> str:
    if timeout:
        return "timeout"
    if status_code == 0:
        return "unknown"
    if blocked_flag(status_code):
        return "blocked"
    if allowed_flag(status_code):
        return "allowed"
    if redirect_flag(status_code):
        return "redirected"
    if client_error_flag(status_code):
        return "client_error"
    if server_error_flag(status_code):
        return "server_error"
    return "unknown"


def classify_attack_detection(
    traffic_type: str,
    attack_type: str,
    detected_attack_type: str,
    zap_alert_types: str = "",
) -> str:
    """Classify whether alert-derived attack labels match the generated payload.

    The generated payload category is the ground truth. ZAP alerts are treated as
    the observed classifier output. A single request can produce multiple alert
    categories, stored in zap_alert_types as a semicolon-separated list.
    """

    if traffic_type != "attack":
        return "not_applicable"

    detected_types = {
        item.strip()
        for item in str(zap_alert_types or detected_attack_type or "").split(";")
        if item.strip() and item.strip() != "none"
    }
    if not detected_types:
        return "missed"
    if attack_type in detected_types:
        return "correct"
    return "incorrect"


class CSVDataLogger:
    """Append-only CSV writer protected by a lock for concurrent traffic."""

    def __init__(self, output_file: Path, run_id: str, reset: bool = True) -> None:
        self.output_file = Path(output_file)
        self.run_id = run_id
        self.output_file.parent.mkdir(parents=True, exist_ok=True)
        self._lock = threading.Lock()
        self._rows: list[dict] = []
        if reset:
            self.reset()
        elif not self.output_file.exists():
            self.reset()

    def reset(self) -> None:
        with self._lock:
            self._rows = []
            with self.output_file.open("w", newline="", encoding="utf-8") as handle:
                writer = csv.DictWriter(handle, fieldnames=CSV_COLUMNS)
                writer.writeheader()

    def rows(self) -> list[dict]:
        with self._lock:
            return list(self._rows)

    def log(
        self,
        environment: EnvironmentConfig,
        observation: RequestObservation,
    ) -> None:
        result = observation.result
        if result == "unknown":
            result = classify_result(observation.status_code, observation.timeout)
        classification_result = observation.classification_result
        if classification_result == "not_applicable" and observation.traffic_type == "attack":
            classification_result = classify_attack_detection(
                observation.traffic_type,
                observation.attack_type,
                observation.detected_attack_type,
                observation.zap_alert_types,
            )

        row = {
            "timestamp": utc_timestamp(),
            "run_id": self.run_id,
            "environment": environment.name,
            "waf_type": environment.waf_type,
            "phase": observation.phase,
            "load_level": observation.load_level,
            "traffic_type": observation.traffic_type,
            "attack_type": observation.attack_type,
            "request_name": observation.request_name,
            "method": observation.method,
            "url": observation.url,
            "status_code": observation.status_code,
            "result": result,
            "response_time_ms": round(observation.response_time_ms, 3),
            "blocked_flag": blocked_flag(observation.status_code),
            "allowed_flag": allowed_flag(observation.status_code),
            "redirect_flag": redirect_flag(observation.status_code),
            "client_error_flag": client_error_flag(observation.status_code),
            "server_error_flag": server_error_flag(observation.status_code),
            "timeout_flag": timeout_flag(observation),
            "detected_attack_type": observation.detected_attack_type,
            "classification_result": classification_result,
            "zap_alert_types": observation.zap_alert_types,
            "zap_alert_names": observation.zap_alert_names,
            "zap_alert_count": observation.zap_alert_count,
            "zap_high_alert_count": observation.zap_high_alert_count,
            "zap_medium_alert_count": observation.zap_medium_alert_count,
            "zap_low_alert_count": observation.zap_low_alert_count,
        }
        with self._lock:
            internal_row = dict(row)
            internal_row["expected_behavior"] = observation.expected_behavior
            self._rows.append(internal_row)
            with self.output_file.open("a", newline="", encoding="utf-8") as handle:
                writer = csv.DictWriter(handle, fieldnames=CSV_COLUMNS)
                writer.writerow(row)
